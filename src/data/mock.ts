/** Build more bookings from the three templates (history, pending, canceled). */
function variant<T extends Booking>(base: T, n: string, patch: Partial<Booking>): T {
  const copy = structuredClone(base);
  const seq = n.padStart(4, '0');
  copy.id = `${base.id.split('-')[0]}-${seq}`;
  copy.ref = base.ref.replace(/\d{4}$/, seq);
  copy.invoice.no = base.invoice.no.replace(/\d{4}$/, seq);
  return Object.assign(copy, patch) as T;
}

